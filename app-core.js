    function getQuizTextInLanguage(card, language) {
      if (!card || !language) return '';
      // Sentence cards store Vietnamese in word, Chinese in meaning and English in chinese.
      if (card.cardType === 'sentence') {
        if (language === 'Tiếng Việt') return String(card.word || '').trim();
        if (language === 'Tiếng Trung') return String(card.meaning || '').trim();
        if (language === 'Tiếng Anh') return String(card.chinese || '').trim();
        return '';
      }
      // Vocabulary cards: word is the source-language entry, meaning is Vietnamese,
      // and chinese is the non-Vietnamese equivalent used by the existing data model.
      if (language === card.lang) return String(card.word || '').trim();
      if (language === 'Tiếng Việt') return String(card.meaning || '').trim();
      if (language === 'Tiếng Trung' || language === 'Tiếng Anh') return String(card.chinese || '').trim();
      return '';
    }

