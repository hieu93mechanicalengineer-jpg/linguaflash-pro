    function toggleSpeechRecognition() {
      if (speechRecognitionBusy && activeSpeechRecognition) {
        try { activeSpeechRecognition.stop(); } catch (_) {}
        return;
      }

      const statusText = document.getElementById('recordStatusText');
      const resultBox = document.getElementById('recognitionResultBox');
      const recognizedTextEl = document.getElementById('recognizedText');
      const feedbackEl = document.getElementById('pronunFeedback');
      const recordBtn = document.getElementById('recordBtn');

      // Native Capacitor recognition is preferred inside Android/iOS apps.
      const nativeRecognition = window.Capacitor?.Plugins?.SpeechRecognition;
      if (nativeRecognition?.start) {
        PRONUNCIATION_TARGETS = getPronunciationPool();
        if (!PRONUNCIATION_TARGETS.length) return;
        const activeTarget = PRONUNCIATION_TARGETS[pronunIndex];
        const recognitionLanguage = activeTarget.practiceLanguage || document.getElementById('pronunLangFilter')?.value || 'Tiếng Trung';
        const nativeLang = recognitionLanguage === 'Tiếng Trung' ? 'zh-CN' : recognitionLanguage === 'Tiếng Việt' ? 'vi-VN' : 'en-US';
        (async () => {
          try {
            if (nativeRecognition.requestPermissions) {
              const perm = await nativeRecognition.requestPermissions();
              const state = perm?.speechRecognition || perm?.microphone || perm?.permission || perm?.state;
              if (state && !['granted','GRANTED','prompt','prompt-with-rationale'].includes(state)) throw new Error('permission-denied');
            }
            if (nativeRecognition.available) { const a = await nativeRecognition.available(); if (a && a.available === false) throw new Error('unavailable'); }
            speechRecognitionBusy = true;
            if (recordBtn) recordBtn.disabled = true;
            if (resultBox) resultBox.classList.add('hidden');
            if (statusText) statusText.textContent = `🎤 Đang lắng nghe (${nativeLang})...`;
            let speechResult = '';
            const res = await nativeRecognition.start({ language: nativeLang, maxResults: 3, partialResults: false, popup: false });
            speechResult = (res?.matches?.[0] || res?.value || '').trim();
            if (!speechResult && nativeRecognition.stop) { const stopped = await nativeRecognition.stop(); speechResult = (stopped?.matches?.[0] || '').trim(); }
            if (!speechResult) throw new Error('no-speech');
            const target = activeTarget?.word?.trim() || '';
            if (recognizedTextEl) recognizedTextEl.textContent = `"${speechResult}"`;
            if (resultBox) resultBox.classList.remove('hidden');
            const clean = v => String(v||'').toLowerCase().replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g,'').trim();
            const ok = clean(speechResult) && clean(target) && (clean(speechResult).includes(clean(target)) || clean(target).includes(clean(speechResult)));
            if (feedbackEl) { feedbackEl.textContent = ok ? '🌟 Phát âm chuẩn xác tuyệt vời! (Perfect Pronunciation!)' : `💡 Bạn vừa nói "${speechResult}". Hãy thử lại để khớp với "${target}" nhé!`; feedbackEl.className = ok ? 'text-sm font-semibold text-emerald-600' : 'text-sm font-semibold text-amber-600'; }
            if (statusText) statusText.textContent = 'Đã nhận diện xong. Bấm micro để thử lại.';
          } catch (err) {
            const code = String(err?.message || err || 'unknown');
            if (statusText) statusText.textContent = code.includes('permission') ? 'Ứng dụng chưa được cấp quyền Microphone / Nhận diện giọng nói.' : getSpeechRecognitionErrorMessage(code);
            showToast(code.includes('permission') ? 'Hãy cấp quyền Microphone cho LinguaFlash Pro.' : 'Chưa nhận diện được giọng nói.', '⚠️');
          } finally { speechRecognitionBusy = false; if (recordBtn) recordBtn.disabled = false; }
        })();
        return;
      }

      const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;

      if (!SpeechRecognition) {
        const msg = 'Trình duyệt này chưa hỗ trợ nhận diện giọng nói trực tiếp. Hãy thử Safari trên iPhone hoặc Chrome trên Android; nếu vẫn không được, cần dùng dịch vụ nhận diện thay thế.';
        if (statusText) statusText.textContent = msg;
        showToast('Trình duyệt chưa hỗ trợ nhận diện giọng nói.', '⚠️');
        return;
      }

      PRONUNCIATION_TARGETS = getPronunciationPool();
      if (!PRONUNCIATION_TARGETS.length) return;
      const activeTarget = PRONUNCIATION_TARGETS[pronunIndex];
      const recognition = new SpeechRecognition();
      activeSpeechRecognition = recognition;
      const recognitionLanguage = activeTarget.practiceLanguage || document.getElementById('pronunLangFilter')?.value || 'Tiếng Trung';
      recognition.lang = recognitionLanguage === 'Tiếng Trung' ? 'zh-CN' : recognitionLanguage === 'Tiếng Việt' ? 'vi-VN' : 'en-US';
      recognition.interimResults = false;
      recognition.maxAlternatives = 1;
      // Mobile browsers may stop listening automatically after a short pause.
      recognition.continuous = false;

      if (resultBox) resultBox.classList.add('hidden');
      if (statusText) statusText.textContent = `🎤 Đang lắng nghe (${recognition.lang})... Hãy nói rõ trong vài giây.`;
      if (recordBtn) recordBtn.disabled = true;
      speechRecognitionBusy = true;

      recognition.onresult = function(event) {
        const transcript = event?.results?.[0]?.[0]?.transcript;
        if (!transcript) {
          if (statusText) statusText.textContent = getSpeechRecognitionErrorMessage('no-speech');
          return;
        }
        const speechResult = transcript.trim();
        const target = PRONUNCIATION_TARGETS[pronunIndex]?.word?.trim() || '';
        if (recognizedTextEl) recognizedTextEl.textContent = `"${speechResult}"`;
        if (resultBox) resultBox.classList.remove('hidden');

        const cleanSpeech = speechResult.toLowerCase().replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g,"").trim();
        const cleanTarget = target.toLowerCase().replace(/[.,\/#!$%\^&\*;:{}=\-_`~()]/g,"").trim();

        if (cleanSpeech && cleanTarget && (cleanSpeech.includes(cleanTarget) || cleanTarget.includes(cleanSpeech))) {
          if (feedbackEl) {
            feedbackEl.textContent = '🌟 Phát âm chuẩn xác tuyệt vời! (Perfect Pronunciation!)';
            feedbackEl.className = 'text-sm font-semibold text-emerald-600';
          }
          showToast('Phát âm xuất sắc!', '🎉');
        } else if (feedbackEl) {
          feedbackEl.textContent = `💡 Bạn vừa nói "${speechResult}". Hãy thử lại để khớp với "${target}" nhé!`;
          feedbackEl.className = 'text-sm font-semibold text-amber-600';
        }
        if (statusText) statusText.textContent = 'Đã nhận diện xong. Bấm micro để thử lại.';
      };

      recognition.onerror = function(event) {
        const code = event?.error || 'unknown';
        const msg = getSpeechRecognitionErrorMessage(code);
        if (statusText) statusText.textContent = msg;
        showToast(msg, '⚠️');
      };

      recognition.onend = function() {
        speechRecognitionBusy = false;
        if (activeSpeechRecognition === recognition) activeSpeechRecognition = null;
        if (recordBtn) recordBtn.disabled = false;
        if (statusText && statusText.textContent.includes('Đang lắng nghe')) {
          statusText.textContent = 'Micro đã dừng. Nếu chưa thấy kết quả, hãy thử nói lại hoặc kiểm tra quyền micro.';
        }
      };

      try {
        recognition.start();
      } catch (error) {
        speechRecognitionBusy = false;
        activeSpeechRecognition = null;
        if (recordBtn) recordBtn.disabled = false;
        const msg = error?.name === 'NotAllowedError'
          ? getSpeechRecognitionErrorMessage('not-allowed')
          : `Không thể khởi động micro (${error?.name || 'lỗi'}). Hãy thử lại trong Safari/Chrome và kiểm tra quyền micro.`;
        if (statusText) statusText.textContent = msg;
        showToast(msg, '⚠️');
      }
    }

    function populateDialogueLessonDropdown(resetLesson = false) {
      const courseSelect = document.getElementById('dialogueCourseSelector');
      const lessonSelect = document.getElementById('dialogueLessonSelector');
      if (!lessonSelect) return;

      const previousCourse = courseSelect ? courseSelect.value : '';
      const previousLesson = lessonSelect.value;
      const courses = [...new Set(Object.values(DIALOGUES_DB).map(lesson => lesson.course || 'Khác'))];

      if (courseSelect) {
        courseSelect.innerHTML = '<option value="ALL">Tất cả chủ đề</option>';
        courses.forEach(course => {
          const option = document.createElement('option');
          option.value = course;
          option.textContent = course;
          courseSelect.appendChild(option);
        });
        courseSelect.value = courses.includes(previousCourse) ? previousCourse :
          (courses.includes('Gia Hân') ? 'Gia Hân' : (courses[0] || 'ALL'));
      }

      const selectedCourse = courseSelect ? courseSelect.value : 'ALL';
      const entries = Object.entries(DIALOGUES_DB).filter(([key, lesson]) =>
        selectedCourse === 'ALL' || (lesson.course || 'Khác') === selectedCourse
      );
      lessonSelect.innerHTML = '';
      entries.forEach(([key, lesson]) => {
        const option = document.createElement('option');
        option.value = key;
        option.textContent = lesson.topic || lesson.title;
        lessonSelect.appendChild(option);
      });
      const validPrevious = entries.some(([key]) => key === previousLesson);
      lessonSelect.value = !resetLesson && validPrevious ? previousLesson : (entries[0]?.[0] || '');
      if (lessonSelect.value) changeDialogueLesson(lessonSelect.value);
    }

