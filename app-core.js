    function handleExcelUpload(event) {
      const file = event.target.files[0];
      if (!file) return;

      const reader = new FileReader();
      reader.onload = function(e) {
        try {
          const data = new Uint8Array(e.target.result);
          const workbook = XLSX.read(data, { type: 'array' });
          const firstSheetName = workbook.SheetNames[0];
          const worksheet = workbook.Sheets[firstSheetName];
          const rows = XLSX.utils.sheet_to_json(worksheet, { defval: '' });

          let added = 0;
          rows.forEach((row, idx) => {
            const word = (row['Từ vựng'] || row['Tu vung'] || row['Word'] || row['Từ vựng (English)'] || '').toString().trim();
            const meaning = (row['Nghĩa tiếng Việt'] || row['Nghia'] || row['Meaning'] || '').toString().trim();
            if (!word || !meaning) return;

            let lang = (row['Ngôn ngữ'] || row['Ngon ngu'] || row['Language'] || '').toString().trim();
            if (!lang) {
              lang = /[一-龥]/.test(word) ? 'Tiếng Trung' : 'Tiếng Anh';
            } else if (lang.toLowerCase().includes('anh') || lang.toLowerCase().includes('en')) {
              lang = 'Tiếng Anh';
            } else {
              lang = 'Tiếng Trung';
            }

            const phonetic = (row['Phiên âm'] || row['Phiên âm / IPA'] || row['Phonetic'] || row['Pinyin'] || '').toString().trim();
            const chinese = (row['Tiếng Trung (Hán tự / Pinyin)'] || row['Tiếng Trung'] || row['Tieng Trung'] || '').toString().trim();
            const example = (row['Ví dụ'] || row['Vi du'] || row['Example'] || '').toString().trim();
            const exampleTrans = (row['Dịch ví dụ'] || row['Dich vi du'] || row['Translation'] || '').toString().trim();
            const topic = (row['Chủ đề'] || row['Chu de'] || row['Topic'] || 'Tiếng Anh - Phần S1').toString().trim();
            const level = (row['Cấp độ'] || row['Cap do'] || row['Level'] || 'Cơ bản').toString().trim();

            const existingIdx = allCards.findIndex(c => c.word.toLowerCase() === word.toLowerCase());
            const newCard = {
              id: 'xl_' + Date.now() + '_' + idx,
              lang, word, phonetic, meaning, chinese, example, exampleTrans, topic, level,
              interval: 0, repetitions: 0, easeFactor: 2.5, nextReview: Date.now()
            };

            if (existingIdx >= 0) {
              allCards[existingIdx] = { ...allCards[existingIdx], ...newCard, id: allCards[existingIdx].id };
            } else {
              allCards.unshift(newCard);
            }
            added++;
          });

          saveData();
          populateCategoryDropdown();
          applyStudyFilters();
          renderManageTable();
          showToast(`Đã nạp thành công ${added} từ vựng!`, '🎉');
          event.target.value = '';
        } catch (err) {
          showToast('Lỗi đọc file Excel!', '❌');
        }
      };
      reader.readAsArrayBuffer(file);
    }


