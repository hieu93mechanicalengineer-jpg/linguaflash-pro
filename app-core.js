    function dedupeExpandedVocabularyCards(cards) {
      // If the same exact vocabulary appears in both a lesson's base topic and its
      // "Từ vựng mở rộng" topic, keep the expanded-vocabulary copy.
      const norm = v => String(v || '').normalize('NFC').toLowerCase().replace(/\s+/g, ' ').trim();
      const baseKey = topic => {
        const t = String(topic || '');
        const m = t.match(/^(Tiếng Trung Huyền Anh\s*-\s*Level\s*\d+\s*-\s*Bài\s*\d+)\s*(?:-\s*Từ vựng mở rộng)?$/i);
        return m ? m[1].replace(/\s+/g, ' ').toLowerCase() : null;
      };
      const contentKey = c => [
        c.cardType || 'vocab', c.word, c.pinyin, c.meaning, c.meaningEn,
        c.chinese, c.chineseText, c.chineseTranslation, c.translation, c.example, c.exampleTrans, c.exampleEn
      ].map(norm).join('|');
      const expanded = new Set();
      cards.forEach(c => {
        const t = String(c.topic || '');
        if (/Từ vựng mở rộng/i.test(t)) {
          const b = baseKey(t);
          if (b) expanded.add(b + '|' + contentKey(c));
        }
      });
      const removed = [];
      const kept = [];
      cards.forEach(c => {
        const t = String(c.topic || '');
        const b = baseKey(t);
        const isExpanded = /Từ vựng mở rộng/i.test(t);
        if (b && !isExpanded && expanded.has(b + '|' + contentKey(c))) removed.push(c);
        else kept.push(c);
      });
      return { cards: kept, removed };
    }

