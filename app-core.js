    function speakFullDialogue(languageKey = 'cn') {
      if (!('speechSynthesis' in window)) {
        showToast('Trình duyệt này chưa hỗ trợ phát âm thanh.', '⚠️');
        return;
      }
      const select = document.getElementById('dialogueLessonSelector');
      const lessonKey = select && select.value ? select.value : Object.keys(DIALOGUES_DB)[0];
      const dlg = DIALOGUES_DB[lessonKey] || DIALOGUES_DB[Object.keys(DIALOGUES_DB)[0]];
      const pieces = dlg.lines.map(line => getDialogueAudioContent(line, languageKey)).filter(audio => audio.text && audio.text.trim());
      if (!pieces.length) {
        showToast(languageKey === 'vn' ? 'Bài này chưa có bản tiếng Việt.' : languageKey === 'en' ? 'Bài này chưa có bản tiếng Anh.' : 'Bài này chưa có nội dung ngôn ngữ gốc.', 'ℹ️');
        return;
      }
      window.speechSynthesis.cancel();
      let index = 0;
      const speakNext = () => {
        if (index >= pieces.length) return;
        const piece = pieces[index++];
        currentUtterance = new SpeechSynthesisUtterance(piece.text);
        currentUtterance.lang = piece.lang;
        currentUtterance.rate = 0.88;
        currentUtterance.onend = speakNext;
        window.speechSynthesis.speak(currentUtterance);
      };
      speakNext();
      showToast(languageKey === 'vn' ? 'Đang phát toàn bộ hội thoại bằng tiếng Việt...' : languageKey === 'en' ? 'Playing the full dialogue in English...' : 'Đang phát toàn bộ hội thoại bằng ngôn ngữ gốc...', '🎧');
    }

