    function checkTypingAnswer() {
      if (quizAnswered) return;
      const card = quizDeck[quizIndex];
      const inp = document.getElementById('quizTypingInput');
      const userVal = inp.value.trim().toLowerCase();
      if (!userVal) return;

      quizAnswered = true;
      inp.disabled = true;
      const reverseTyping = document.getElementById('quizModeSelect').value === 'typing_reverse';
      const targetRaw = reverseTyping ? getQuizTargetText(card) : getQuizSupportText(card);
      const normalizeAnswer = value => String(value || '').trim().toLowerCase().replace(/[\s\u3000]+/g, ' ');
      const targetWord = normalizeAnswer(targetRaw);
      const isCorrect = normalizeAnswer(userVal) === targetWord;

      if (isCorrect) {
        quizScore++;
        updateCardFromQuiz(card, true);
        showQuizFeedback(true, reverseTyping
          ? (currentUiLang === 'en' ? `Correct! ${getQuizTargetLanguage()}: "${targetRaw}"` : currentUiLang === 'zh' ? `正确！${(QUIZ_LANGUAGE_LABELS[getQuizTargetLanguage()] || {}).zh || getQuizTargetLanguage()}答案："${targetRaw}"` : `Chính xác! Đáp án ${getQuizTargetLanguage()}: "${targetRaw}"`)
          : (currentUiLang === 'en' ? `Correct! ${getQuizSupportLanguage()}: "${targetRaw}"` : currentUiLang === 'zh' ? `正确！${(QUIZ_LANGUAGE_LABELS[getQuizSupportLanguage()] || {}).zh || getQuizSupportLanguage()}答案："${targetRaw}"` : `Chính xác! Đáp án ${getQuizSupportLanguage()}: "${targetRaw}"`));
      } else {
        updateCardFromQuiz(card, false);
        showQuizFeedback(false, `Chưa chính xác. Đáp án đúng là: "${targetRaw}"`);
      }
    }

    function updateCardFromQuiz(card, correct) {
      const DAY_MS = 24 * 60 * 60 * 1000;
      if (correct) {
        card.interval = (card.interval || 0) === 0 ? 2 : Math.round(card.interval * 2);
        card.repetitions = (card.repetitions || 0) + 1;
        card.nextReview = Date.now() + card.interval * DAY_MS;
      } else {
        card.interval = 0;
        card.repetitions = 0;
        card.nextReview = Date.now();
        card.lastAnswerQuality = 0;
        card.needsReview = true;
      }
      if (correct) { card.lastAnswerQuality = 2; card.needsReview = false; }
      card.lastReviewedAt = Date.now();
      if (card.quizOnly === true && card.quizSource === 'giahan_dialogue') {
        const progressMap = getDialogueQuizProgressMap();
        progressMap[card.id] = {
          interval: Number(card.interval || 0),
          repetitions: Number(card.repetitions || 0),
          easeFactor: Number(card.easeFactor || 2.5),
          nextReview: Number(card.nextReview || 0),
          lastAnswerQuality: card.lastAnswerQuality,
          needsReview: card.needsReview === true,
          lastReviewedAt: Number(card.lastReviewedAt || Date.now())
        };
      }
      userStats.totalReviews = (userStats.totalReviews || 0) + 1;
      saveData();
    }

