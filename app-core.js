    function parseCategoryAndTopic(topicStr) {
      if (!topicStr) return { cat: 'Chung', sub: 'Chung' };
      // Explicitly support the course hierarchy used by the Gia Han textbook.
      const normalized = String(topicStr).trim();
      if (/^Gia Hân\s*-\s*Trung cấp [12](?:\s*-|$)/i.test(normalized)) {
        return { cat: 'Gia Hân', sub: normalized.replace(/^Gia Hân\s*-\s*/i, '').trim() };
      }
      const parts = normalized.split('-');
      if (parts.length >= 2) {
        return { cat: parts[0].trim(), sub: parts.slice(1).join('-').trim() };
      }
      return { cat: 'Chung', sub: normalized };
    }

