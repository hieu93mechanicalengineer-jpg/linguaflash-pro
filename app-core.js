    function rateCard(quality) {
      if (filteredDeck.length === 0) return;
      const card = filteredDeck[currentIndex];
      let rep = card.repetitions || 0;
      let ivl = card.interval || 0;
      let ef = card.easeFactor || 2.5;
      const DAY_MS = 24 * 60 * 60 * 1000;

      const isNewForToday = (card.repetitions || 0) === 0;
      if (quality === 0) {
        rep = 0; ivl = 0;
        card.nextReview = Date.now() + 10 * 60 * 1000;
        showToast(`Sẽ nhắc ôn lại sau 10 phút`, '🔄');
      } else if (quality === 1) {
        ivl = Math.max(1, Math.round((ivl || 1) * 1.2));
        rep += 1; ef = Math.max(1.3, ef - 0.15);
        card.nextReview = Date.now() + ivl * DAY_MS;
        showToast(`Đã lên lịch ôn sau ${ivl} ngày`, '📅');
      } else if (quality === 2) {
        ivl = ivl === 0 ? 1 : (ivl === 1 ? 3 : Math.round(ivl * ef));
        rep += 1;
        card.nextReview = Date.now() + ivl * DAY_MS;
        showToast(`Ôn lại sau ${ivl} ngày`, '✅');
      } else if (quality === 3) {
        ivl = ivl === 0 ? 4 : Math.round((ivl || 2) * ef * 1.4);
        rep += 1; ef += 0.15;
        card.nextReview = Date.now() + ivl * DAY_MS;
        showToast(`Nhắc lại sau ${ivl} ngày`, '🌟');
      }

      card.repetitions = rep;
      card.lastReviewedAt = Date.now();
      card.lastAnswerQuality = quality;
      card.interval = ivl;
      card.easeFactor = ef;
      userStats.totalReviews = (userStats.totalReviews || 0) + 1;
      saveData();

      if (quality === 0) {
        // A missed card stays inside this 20-card batch and returns to the queue.
        const insertAt = Math.min(currentIndex + 2, filteredDeck.length);
        filteredDeck.splice(insertAt, 0, card);
        showToast('Thẻ này sẽ được ôn lại trong nhóm 20 thẻ hiện tại.','🔄');
        currentIndex++; renderCurrentCard(); return;
      }
      if (!activeStudyCompletedIds.has(card.id)) {
        activeStudyCompletedIds.add(card.id);
        const progress = getDailyProgress();
        const bucket = isNewForToday ? 'newIds' : 'reviewIds';
        const limit = isNewForToday ? getDailyGoalSettings().newLimit : getDailyGoalSettings().reviewLimit;
        const ids = new Set(progress[bucket] || []);
        if (ids.size < limit) ids.add(card.id);
        progress[bucket] = [...ids]; saveDailyProgress(progress); updateDailyGoalSummary();
        if ((isNewForToday && ids.size >= limit) || (!isNewForToday && ids.size >= limit)) showToast('🎉 Đã hoàn thành mục tiêu hôm nay cho nhóm này!','🏆');
      }
      if (document.getElementById('studyDueOnly').checked) { applyStudyFilters(); } else { nextCard(); }
    }

    async function speakText(text, langLabel) {
      if (!text || !String(text).trim()) return;
      const lang = (langLabel === 'Tiếng Anh') ? 'en-US' : ((langLabel === 'Tiếng Việt') ? 'vi-VN' : 'zh-CN');
      // Native first when packaged by Capacitor; web SpeechSynthesis remains the browser fallback.
      try {
        const nativeTts = window.Capacitor?.Plugins?.TextToSpeech;
        if (nativeTts?.speak) {
          if (nativeTts.stop) { try { await nativeTts.stop(); } catch (_) {} }
          await nativeTts.speak({ text: String(text), lang, rate: 0.92, pitch: 1.0, volume: 1.0, category: 'playback', queueStrategy: 0 });
          return;
        }
      } catch (err) { console.warn('Native TTS failed, using web fallback:', err); }
      if (!('speechSynthesis' in window)) {
        showToast('Thiết bị chưa có bộ đọc văn bản phù hợp.', '⚠️');
        return;
      }
      try {
        window.speechSynthesis.cancel();
        const utter = new SpeechSynthesisUtterance(String(text));
        utter.lang = lang; utter.rate = 0.92;
        const voices = window.speechSynthesis.getVoices?.() || [];
        const exact = voices.find(v => (v.lang || '').toLowerCase() === lang.toLowerCase());
        const family = voices.find(v => (v.lang || '').toLowerCase().startsWith(lang.slice(0,2).toLowerCase()));
        if (exact || family) utter.voice = exact || family;
        utter.onerror = () => showToast('Không phát được âm thanh. Hãy kiểm tra giọng đọc của điện thoại.', '⚠️');
        window.speechSynthesis.speak(utter);
      } catch (err) { showToast('Không phát được âm thanh trên thiết bị này.', '⚠️'); }
    }

